/**
 * build-place-index — snapshot the place ids + wizard tags this repo needs from
 * shared-data into place-index.json (public venue facts only: id + wizards[]).
 *
 * shared-data is not an installed dependency here (and CI has no checkout of
 * it), so the backfill, the fetcher and the gate read the committed snapshot.
 * Regenerate (offline, no model call) when shared-data moves:
 *
 *   SHARED_DATA_DIR=~/shared-data npx tsx scripts/build-place-index.ts
 *
 * The snapshot pins shared-data's package version and git sha.
 */
import { writeFileSync } from "node:fs";
import { resolve } from "node:path";
import { execSync } from "node:child_process";
import { homedir } from "node:os";
import type { PlaceIndex } from "../lib/place";

const REPO_ROOT = resolve(__dirname, "..");
const SD = resolve(process.env.SHARED_DATA_DIR ?? resolve(homedir(), "shared-data"));

type Row = { id?: string; wizards?: string[] };

function table(rows: Row[]): Record<string, string[]> {
  const out: Record<string, string[]> = {};
  for (const r of rows) {
    if (!r.id) throw new Error("build-place-index: a shared-data row has no id");
    if (r.id in out) throw new Error(`build-place-index: duplicate id ${r.id} inside one source`);
    out[r.id] = [...(r.wizards ?? [])].sort();
  }
  return out;
}

async function main() {
  // eslint-disable-next-line @typescript-eslint/no-require-imports
  const sd = await import(resolve(SD, "src/index.ts"));
  const sha = execSync("git rev-parse HEAD", { cwd: SD, encoding: "utf8" }).trim();
  // eslint-disable-next-line @typescript-eslint/no-require-imports
  const version = JSON.parse(require("node:fs").readFileSync(resolve(SD, "package.json"), "utf8")).version as string;
  const index: PlaceIndex = {
    note: "Generated by scripts/build-place-index.ts from shared-data (public venue ids + wizards tags only). Do not hand-edit.",
    sharedData: { version, sha },
    places: {
      destination: table(sd.sharedDestinations),
      golfDestination: table(sd.SHARED_GOLF_DESTINATIONS),
      residence: table(sd.ALL_RESIDENCES),
      ooExperience: table([
        ...sd.ooExperiences, ...sd.ooHeroExpAir, ...sd.ooHeroExpWater, ...sd.ooHeroExpWinter,
        ...sd.ooPoolExpAir, ...sd.ooPoolExpWater, ...sd.ooPoolExpWinter,
      ]),
      ooOuting: table([...sd.ooSignatureOutings, ...sd.ooHeroOutingsUrban, ...sd.ooPoolOutingsUrban]),
      proposalSpot: table(sd.PROPOSAL_SPOTS_DATA),
    },
  };
  writeFileSync(resolve(REPO_ROOT, "place-index.json"), JSON.stringify(index, null, 2) + "\n", "utf8");
  const n = Object.entries(index.places).map(([k, v]) => `${k}=${Object.keys(v).length}`).join(" ");
  console.log(`wrote place-index.json @ shared-data ${version} ${sha.slice(0, 7)}: ${n}`);
}
main().catch((e) => { console.error(e); process.exit(1); });
